import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const issuer = process.env.SPILLED_OPERATOR_OIDC_ISSUER?.replace(/\/$/, "");
const applicationID = process.env.SPILLED_OPERATOR_OIDC_CLIENT_ID;
if (!issuer || !applicationID || !issuer.startsWith("https://")) {
  throw new Error("HTTPS SPILLED_OPERATOR_OIDC_ISSUER and SPILLED_OPERATOR_OIDC_CLIENT_ID are required.");
}
const discovery = await fetch(`${issuer}/.well-known/openid-configuration`, {
  signal: AbortSignal.timeout(15_000),
});
if (!discovery.ok) throw new Error(`OIDC discovery failed with ${discovery.status}.`);
const metadata = await discovery.json();
if (metadata.issuer !== issuer || typeof metadata.jwks_uri !== "string") {
  throw new Error("OIDC discovery issuer/JWKS metadata does not match.");
}
const target = resolve("convex/operatorAuth.generated.ts");
await writeFile(target, `import type { AuthProvider } from "convex/server";

// Generated by scripts/configure-operator-oidc.mjs.
export const operatorAuthProviders: AuthProvider[] = [{
  domain: ${JSON.stringify(issuer)},
  applicationID: ${JSON.stringify(applicationID)},
}];
`, { encoding: "utf8", mode: 0o600 });
console.log(`Configured Convex operator OIDC issuer ${issuer}.`);
